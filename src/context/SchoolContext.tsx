  const resolveSchoolKey = (
    schoolIdOrName: string | undefined,
    schoolsMap: Record<string, SchoolData>,
  ): string | null => {
    if (!schoolIdOrName) return null;
    const raw = String(schoolIdOrName).trim();
    if (!raw) return null;
    const canonical = canonicalSchoolKey(raw);
    if (canonical && schoolsMap[canonical]) return canonical;
    if (schoolsMap[raw]) return raw;

    // Check with extractSchoolFromText (handles "בית הספר של העתיד (בן שמן)", etc.)
    const extracted = extractSchoolFromText(raw);
    const extractedId = extracted ? canonicalSchoolKey(extracted.schoolId) || extracted.schoolId : "";
    if (extractedId && schoolsMap[extractedId]) {
      return extractedId;
    }

    const canonicalFromName = canonicalizeSchoolId(raw);
    if (schoolsMap[canonicalFromName]) return canonicalFromName;

    const clean = raw
      .toLowerCase()
      .replace(/['"״\-_]/g, "")
      .trim();

    // Prevent generic phrases like "בית ספר" or "יסודי" from matching randomly
    const genericPhrases = [
      "ביתספר",
      "ביתהספר",
      "ביס",
      "יסודי",
      "ממלכתי",
      "העתיד",
      "שלהעתיד",
      "ביתהספרשלהעתיד",
      "ביתספרשלהעתיד",
      "תלמידים",
    ];
    if (genericPhrases.includes(clean) || clean.length < 3) {
      return null;
    }

    for (const [key, val] of Object.entries(schoolsMap)) {
      const keyClean = key
        .toLowerCase()
        .replace(/['"״\-_]/g, "")
        .trim();
      const nameClean = val.school.name
        .toLowerCase()
        .replace(/['"״\-_]/g, "")
        .trim();

      // Check specific distinct school tokens
      if (
        (key.includes("ben-shemen") && (clean.includes("שמן") || clean.includes("benshemen"))) ||
        (key.includes("navon") && (clean.includes("נבון") || clean.includes("navon"))) ||
        (key.includes("lapid") && (clean.includes("לפיד") || clean.includes("המה") || clean.includes("המד")))
      ) {
        return key;
      }

      if (clean === keyClean || clean === nameClean) {
        return key;
      }
    }
    return null;
  };

  const importStudents = (
    imported: Student[],
    modeOrReplace: StudentImportMode | boolean = "merge",
    options?: ImportStudentsOptions,
  ) => {
    const mode: StudentImportMode =
      typeof modeOrReplace === "boolean"
        ? modeOrReplace
          ? "replace"
          : "merge"
        : modeOrReplace || options?.mode || "merge";

    const targetSchoolId = options?.targetSchoolId || currentSchoolId;

    setSchools((prev) => {
      // 1. Group imported students by detected schoolId (resolved against known schools in prev)
      const studentsBySchool: Record<string, Student[]> = {};

      imported.forEach((student) => {
        const explicitOtherSchool = student.schoolId && student.schoolId !== targetSchoolId
          ? resolveSchoolKey(student.schoolId, prev)
          : null;

        const resolvedKey =
          explicitOtherSchool ||
          (student.schoolName ? resolveSchoolKey(student.schoolName, prev) : null) ||
          targetSchoolId;

        if (!studentsBySchool[resolvedKey]) {
          studentsBySchool[resolvedKey] = [];
        }
        studentsBySchool[resolvedKey].push({
          ...student,
          schoolId: resolvedKey,
          schoolName: prev[resolvedKey]?.school.name || student.schoolName,
        });
      });

      const updatedSchools: Record<string, SchoolData> = { ...prev };

      // In replace mode, if targetSchoolId is specified, ensure targetSchoolId is updated and replaced!
      const schoolsToUpdate = new Set<string>(Object.keys(studentsBySchool));
      if (mode === "replace" && targetSchoolId && !schoolsToUpdate.has(targetSchoolId)) {
        schoolsToUpdate.add(targetSchoolId);
      }

      schoolsToUpdate.forEach((schoolKey) => {
        const schoolStudents = studentsBySchool[schoolKey] || [];
        const currentData = prev[schoolKey];
        if (!currentData) return;

        let newStudents: Student[] = [];
        let registrationsToKeep = currentData.registrations;
        let placementsToKeep = currentData.placements;

        if (mode === "replace") {
          // Full replacement: Deduplicate by ID and replace all students
          const seen = new Set<string>();
          newStudents = schoolStudents.filter((s) => {
            const clean = s.id ? s.id.trim() : "";
            if (!clean || seen.has(clean)) return false;
            seen.add(clean);
            return true;
          });

          // Clean up registrations & placements for students that were removed
          const newStudentIds = new Set(newStudents.map((s) => s.id));
          registrationsToKeep = currentData.registrations.filter((r) =>
            newStudentIds.has(r.studentId),
          );
          placementsToKeep = currentData.placements.filter((p) =>
            newStudentIds.has(p.studentId),
          );
        } else if (mode === "add_only") {
          // Only add students not already in the system
          const existingIds = new Set(currentData.students.map((s) => s.id));
          const onlyNew = schoolStudents.filter((s) => !existingIds.has(s.id));
          newStudents = [...currentData.students, ...onlyNew];
        } else if (mode === "sync_changes") {
          // Sync changes:
          // 1. New students added, existing students updated
          // 2. Missing students (or explicit delete IDs) deleted
          const importedMap = new Map<string, Student>(
            schoolStudents.map((s) => [s.id, s]),
          );
          const explicitDeletes = options?.deleteStudentIdsBySchool;
          const deleteSet = explicitDeletes
            ? new Set(explicitDeletes[schoolKey] || [])
            : new Set(
                currentData.students
                  .filter((s) => !importedMap.has(s.id))
                  .map((s) => s.id),
              );

          // Retain and update existing students not in deleteSet
          const retainedAndUpdated = currentData.students
            .filter((s) => !deleteSet.has(s.id))
            .map((existing) => {
              const updated = importedMap.get(existing.id);
              return updated ? { ...existing, ...updated } : existing;
            });

          // Add completely new students
          const existingIds = new Set(currentData.students.map((s) => s.id));
          const brandNew = schoolStudents.filter((s) => !existingIds.has(s.id));

          newStudents = [...retainedAndUpdated, ...brandNew];

          // Clean up registrations & placements for deleted students
          registrationsToKeep = currentData.registrations.filter(
            (r) => !deleteSet.has(r.studentId),
          );
          placementsToKeep = currentData.placements.filter(
            (p) => !deleteSet.has(p.studentId),
          );
        } else {
          // 'merge' (default): Add new students, update existing students, never delete
          const existingMap = new Map<string, Student>(
            currentData.students.map((s) => [s.id, s]),
          );
          schoolStudents.forEach((s) => {
            const existing = existingMap.get(s.id);
            if (existing) {
              existingMap.set(s.id, { ...existing, ...s });
            } else {
              existingMap.set(s.id, s);
            }
          });
          newStudents = Array.from(existingMap.values());
        }

        const updatedData: SchoolData = {
          ...currentData,
          students: newStudents,
          registrations: registrationsToKeep,
          placements: placementsToKeep,
        };

        updatedSchools[schoolKey] = updatedData;
        const replaceStudents = mode === "replace";
        persistSchoolChange(schoolKey, currentData, updatedData, {
          replaceStudents,
          ...(mode === "replace"
            ? { reviveStudentIds: newStudents.map((student) => student.id).filter(Boolean) }
            : {}),
          ...(mode === "sync_changes"
            ? { deleteStudentIds: diffDeletions(currentData, updatedData).deleteStudentIds }
            : {}),
        });
        try {
          localStorage.removeItem(`saved_students_${schoolKey}`);
        } catch (e) {}
      });

      // If a student is explicitly assigned to another existing school, move their
      // registrations with them. Never drop the registration on the floor.
      const studentTargetSchoolMap = new Map<string, string>();
      Object.entries(studentsBySchool).forEach(([sKey, sList]) => {
        sList.forEach((s) => {
          const target = canonicalSchoolKey(sKey) || sKey;
          if (updatedSchools[target]) studentTargetSchoolMap.set(s.id, target);
        });
      });

      Object.keys(updatedSchools).forEach((schoolKey) => {
        const schoolData = updatedSchools[schoolKey];
        if (!schoolData) return;

        const foreignStudentIds = new Set<string>();
        schoolData.students.forEach((s) => {
          const targetSchool = studentTargetSchoolMap.get(s.id);
          if (targetSchool && targetSchool !== schoolKey && updatedSchools[targetSchool]) {
            foreignStudentIds.add(s.id);
          }
        });

        if (foreignStudentIds.size > 0) {
          foreignStudentIds.forEach((studentId) => {
            const targetSchool = studentTargetSchoolMap.get(studentId);
            if (!targetSchool) return;
            const targetData = updatedSchools[targetSchool];
            const movingRegs = schoolData.registrations.filter((r) => r.studentId === studentId);
            const movingPlacements = schoolData.placements.filter((p) => p.studentId === studentId);
            const regMap = new Map<string, Registration>();
            (targetData.registrations || []).forEach((r) => regMap.set(r.studentId, r));
            movingRegs.forEach((r) => {
              const existing = regMap.get(r.studentId);
              regMap.set(r.studentId, existing ? preferRegistration(existing, r) : r);
            });
            const placementMap = new Map<string, Placement>();
            (targetData.placements || []).forEach((p) => placementMap.set(p.id, p));
            movingPlacements.forEach((p) => {
              if (!placementMap.has(p.id)) placementMap.set(p.id, p);
            });
            updatedSchools[targetSchool] = {
              ...targetData,
              registrations: Array.from(regMap.values()),
              placements: Array.from(placementMap.values()),
            };
          });

          const cleanedData: SchoolData = {
            ...schoolData,
            students: schoolData.students.filter((s) => !foreignStudentIds.has(s.id)),
            registrations: schoolData.registrations.filter((r) => !foreignStudentIds.has(r.studentId)),
            placements: schoolData.placements.filter((p) => !foreignStudentIds.has(p.studentId)),
          };
          updatedSchools[schoolKey] = cleanedData;
          persistSchoolChange(schoolKey, schoolData, cleanedData);
          const targetIds = new Set(
            Array.from(foreignStudentIds)
              .map((studentId) => studentTargetSchoolMap.get(studentId))
              .filter((id): id is string => !!id),
          );
          targetIds.forEach((targetId) => {
            persistSchoolChange(targetId, prev[targetId], updatedSchools[targetId]);
          });
        }
      });

      return updatedSchools;
    });
  };

