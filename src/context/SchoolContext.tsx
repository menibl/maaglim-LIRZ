  const importActivities = (
    imported: Activity[],
    modeOrReplace: ActivityImportMode | boolean = "sync_changes",
    options?: ImportActivitiesOptions,
  ) => {
    const mode: ActivityImportMode =
      typeof modeOrReplace === "boolean"
        ? modeOrReplace
          ? "replace"
          : "merge"
        : modeOrReplace;

    updateCurrentSchoolData((prev) => {
      if (mode === "replace") {
        return { ...prev, activities: imported };
      }

      const existingList = [...prev.activities];
      const normalize = (s: string) =>
        s.trim().toLowerCase().replace(/[\s_'"״\.\-]/g, "");

      const matchedExistingIds = new Set<string>();
      const finalActivities: Activity[] = [];

      imported.forEach((imp, idx) => {
        // 1. Try exact ID match
        let existing = existingList.find(
          (a) => a.id.toLowerCase() === imp.id.toLowerCase(),
        );

        // 2. Try match by normalized name + slot
        if (!existing) {
          existing = existingList.find(
            (a) =>
              !matchedExistingIds.has(a.id) &&
              normalize(a.name) === normalize(imp.name) &&
              a.slotNumber === imp.slotNumber,
          );
        }

        // 3. Try match by normalized name only
        if (!existing) {
          existing = existingList.find(
            (a) =>
              !matchedExistingIds.has(a.id) &&
              normalize(a.name) === normalize(imp.name),
          );
        }

        if (existing) {
          matchedExistingIds.add(existing.id);
          if (mode === "add_only") {
            finalActivities.push(existing);
          } else {
            // Update existing with imported changes (preserving stable existing ID)
            finalActivities.push({
              ...existing,
              ...imp,
              id: existing.id,
            });
          }
        } else {
          // New activity
          const newId =
            imp.id && !imp.id.startsWith("ACT-EX-")
              ? imp.id
              : `act-${imp.slotNumber || 1}-${Date.now().toString(36)}-${idx}`;
          finalActivities.push({
            ...imp,
            id: newId,
          });
        }
      });

      // Handle existing activities not in imported file
      const deleteIdSet = new Set(options?.deleteActivityIds || []);
      const unmatchedExisting = existingList.filter(
        (a) => !matchedExistingIds.has(a.id),
      );

      if (mode === "sync_changes") {
        unmatchedExisting.forEach((a) => {
          if (!deleteIdSet.has(a.id)) {
            finalActivities.push(a);
          }
        });
      } else if (mode === "merge" || mode === "add_only") {
        unmatchedExisting.forEach((a) => {
          finalActivities.push(a);
        });
      }

      const cleanedActivities = finalActivities.map((act) => {
        const isMolecular =
          act.name.includes("בישול מולקולרי") ||
          act.name.includes("שעתיים רצופות");
        const isDoubleSlot =
          isMolecular &&
          (act.slotNumber === 2 || act.startTime?.includes("שניה ושלישית"));
        const cleanSlotName = isDoubleSlot
          ? "שעה שניה ושלישית"
          : act.slotNumber === 1
            ? "שעה ראשונה"
            : act.slotNumber === 2
              ? "שעה שניה"
              : "שעה שלישית";
        return {
          ...act,
          startTime: cleanSlotName,
          endTime: "",
        };
      });

      return { ...prev, activities: cleanedActivities };
    });
  };

